OUTPUT_DIR = ROOT / "apps" / "powerpoint" / "src"
JSON_OUTPUT = ROOT / "shared" / "iconaid" / "iconaid-ppt-data.json"

# Maximum icons per VBA module to stay under VBA limits
ICONS_PER_MODULE = 200


def load_catalog() -> dict:
    """Load the unified catalog."""
    with open(CATALOG_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


def simplify_path(path_d: str) -> str:
    """Simplify SVG path for VBA storage (remove extra whitespace)."""
    # Normalize whitespace
    path_d = " ".join(path_d.split())
    # Remove spaces around commands
    path_d = re.sub(r'\s*([MLHVCSQTAZ])\s*', r'\1', path_d, flags=re.IGNORECASE)
    # Add space between numbers where needed (for negative numbers)
    path_d = re.sub(r'(\d)-', r'\1 -', path_d)
    return path_d


def create_icon_record(icon: dict, index: int) -> dict:
    """Create a compact icon record for VBA."""
    # Combine all paths into one string, separated by |
    paths = icon.get("paths", icon.get("svg_paths", []))
    
    # Filter out empty/background paths
    filtered_paths = []
    for p in paths:
        p = p.strip()
        # Skip background rectangle paths
        if p.startswith("M0 0") and "H0" in p:
            continue
        if p.startswith("M0 0h24v24H0"):
            continue
        if not p:
            continue
        filtered_paths.append(simplify_path(p))
    
    # Build search text
    search_parts = [
        icon["name"].lower(),
        icon.get("category", "").lower(),
        " ".join(icon.get("tags", [])[:10]),
    ]
    search_text = " ".join(search_parts)
    
    return {
        "i": index,  # index
        "id": icon["id"],
        "n": icon["name"],  # name
        "c": icon.get("category", "General"),  # category
        "s": icon.get("source", ""),  # source
        "l": icon.get("license", "MIT"),  # license
        "p": filtered_paths,  # paths
        "t": search_text[:200],  # truncated search text
    }


def generate_vba_module(module_num: int, icons: list[dict]) -> str:
    """Generate a VBA module containing icon data."""
    lines = [
        f'Attribute VB_Name = "modIconData{module_num:02d}"',
        "' Generated by scripts/build_unified_iconaid.py",
        "' Part of the unified IconAid catalog with 10,724 icons",
        "Option Explicit",
        "",
        f"' Icons {icons[0]['i']} to {icons[-1]['i']} ({len(icons)} icons)",
        "",
        f"Public Function GetIconData{module_num:02d}(ByVal idx As Long) As String",
        "    Select Case idx",
    ]
    
    for icon in icons:
        # Escape paths for VBA string
        paths_str = "|".join(icon["p"])
        # Escape quotes
        paths_str = paths_str.replace('"', '""')
        
        # Format: index|id|name|category|paths
        record = f'{icon["id"]}|{icon["n"]}|{icon["c"]}|{paths_str}'
        
        # Truncate if too long for VBA
        if len(record) > 1000:
            # Keep only first few paths
            short_paths = icon["p"][:3]
            paths_str = "|".join(short_paths)
            record = f'{icon["id"]}|{icon["n"]}|{icon["c"]}|{paths_str}'
        
        lines.append(f'        Case {icon["i"]}: GetIconData{module_num:02d} = "{record}"')
    
    lines.extend([
        "    End Select",
        "End Function",
        "",
    ])
    
    return "\n".join(lines)


