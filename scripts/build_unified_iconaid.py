def main():
    print("=" * 60)
    print("BUILDING UNIFIED ICONAID FOR POWERPOINT")
    print("=" * 60)
    
    # Load catalog
    print("\nLoading unified catalog...")
    catalog = load_catalog()
    icons = catalog["icons"]
    print(f"Total icons: {len(icons)}")
    
    # Create icon records
    print("\nCreating icon records...")
    records = []
    for i, icon in enumerate(icons, 1):
        record = create_icon_record(icon, i)
        if record["p"]:  # Only include icons with paths
            records.append(record)
    
    print(f"Icons with valid paths: {len(records)}")
    
    # Split into modules
    num_modules = (len(records) + ICONS_PER_MODULE - 1) // ICONS_PER_MODULE
    print(f"VBA modules needed: {num_modules}")
    
    # Generate VBA modules
    print("\nGenerating VBA modules...")
    for mod_num in range(1, num_modules + 1):
        start_idx = (mod_num - 1) * ICONS_PER_MODULE
        end_idx = min(start_idx + ICONS_PER_MODULE, len(records))
        module_icons = records[start_idx:end_idx]
        
        vba_code = generate_vba_module(mod_num, module_icons)
        output_path = OUTPUT_DIR / f"modIconData{mod_num:02d}.bas"
        output_path.write_text(vba_code, encoding="utf-8")
        print(f"  Generated {output_path.name} ({len(module_icons)} icons)")
    
    # Generate main module
    print("\nGenerating main module...")
    categories = catalog.get("categories", [])
    main_code = generate_main_module(len(records), num_modules, categories)
    main_path = OUTPUT_DIR / "modIconAidUnified.bas"
    main_path.write_text(main_code, encoding="utf-8")
    print(f"  Generated {main_path.name}")
    
    # Save JSON for other uses
    print("\nSaving JSON data...")
    json_data = {
        "totalIcons": len(records),
        "categories": categories,
        "icons": records,
    }
    with open(JSON_OUTPUT, "w", encoding="utf-8") as f:
        json.dump(json_data, f, indent=2)
    print(f"  Saved {JSON_OUTPUT}")
    
    print("\n" + "=" * 60)
    print("SUMMARY")
    print("=" * 60)
    print(f"Total icons: {len(records):,}")
    print(f"VBA modules: {num_modules}")
    print(f"Categories: {len(categories)}")
    print("\nAll icons support:")
    print("  ✓ Customizable stroke color")
    print("  ✓ Customizable fill color")
    print("  ✓ Customizable stroke width")
    print("  ✓ Consistent 24×24 proportional sizing")
    print("  ✓ Works offline (all data embedded in VBA)")


if __name__ == "__main__":
    main()
